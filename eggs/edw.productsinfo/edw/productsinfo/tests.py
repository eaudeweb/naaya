import json

from zope.component import getMultiAdapter
from zope.interface import alsoProvides
from zope.publisher.interfaces.browser import IDefaultBrowserLayer

from Products.Naaya.tests.NaayaTestCase import NaayaTestCase


class ProductsInfoTest(NaayaTestCase):
    """ The products.info view described in README.txt """

    def test_token(self):
        request = self.portal.REQUEST
        alsoProvides(request, IDefaultBrowserLayer)
        view = getMultiAdapter((self.portal, request), name='products.info')
        # the key is added at Zope startup; use a known value for the test
        old = self.app.getProperty('edw-productsinfo-key')
        if old is None:
            self.assertEqual(json.loads(view.publishTraverse(view.request, '123')),
                             {'error': 'Unauthorized: Token not set on this instance'})
            self.app.manage_addProperty(id='edw-productsinfo-key', type='string',
                                        value='md5autogeneratedkey')
        else:
            self.app._updateProperty('edw-productsinfo-key', 'md5autogeneratedkey')
        try:
            self.assertEqual(json.loads(view.publishTraverse(view.request, '123')),
                             {'error': 'Invalid authentication token'})
            products = json.loads(view.publishTraverse(view.request, 'md5autogeneratedkey'))
            self.assertTrue(products)
            self.assertEqual(set(products[0]), {'version', 'name'})
        finally:
            if old is None:
                self.app.manage_delProperties(['edw-productsinfo-key'])
            else:
                self.app._updateProperty('edw-productsinfo-key', old)
